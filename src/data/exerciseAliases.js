export function normalizeExerciseKey(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/(^|\s)\d+\s*(раз|повтор(?:а|ов|ений)?|сек(?:унд(?:а|ы)?)?|мин(?:ут(?:а|ы)?)?)(?=\s|$)/g, " ")
    .replace(/техника выполнения упражнени[яй]/g, " ")
    .replace(/[.,;:!?()[\]{}"«»]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

