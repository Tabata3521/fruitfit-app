export function buildUtcPushSchedule({
  now = new Date(),
  days = 7,
  timezoneOffsetMinutes = 180,
  userId = "",
  recentMessageIds = [],
  recentBodies = [],
  previousBody = "",
} = {}) {
  const localNow = new Date(now.getTime() + timezoneOffsetMinutes * 60_000);
  const startYear = localNow.getUTCFullYear();
  const startMonth = localNow.getUTCMonth();
  const startDate = localNow.getUTCDate();
  const blockedIds = new Set((recentMessageIds || []).filter(Boolean));
  const blockedBodies = new Set([previousBody, ...(recentBodies || [])].filter(Boolean));
  const events = [];

  for (let dayOffset = 0; dayOffset < days; dayOffset += 1) {
    const localDay = new Date(Date.UTC(startYear, startMonth, startDate + dayOffset));
    const dateKey = formatUtcDateKey(localDay);
    const slots = slotsForLocalDay(localDay);

    for (const slot of slots) {
      const scheduledAt = new Date(Date.UTC(startYear, startMonth, startDate + dayOffset, slot.hour, slot.minute) - timezoneOffsetMinutes * 60_000);
      if (scheduledAt < now) continue;

      const message = pickPushMessage({
        kind: slot.kind,
        seed: `${userId || "anon"}:${dateKey}:${slot.key}`,
        blockedIds,
        blockedBodies,
      });
      blockedIds.add(message.id);
      blockedBodies.add(message.body);
      events.push(formatScheduleEvent({ slot, message, dateKey, scheduledAt, timezoneOffsetMinutes }));
    }
  }

  return events;
}

export function buildUtcMotivationSchedule(options = {}) {
  return buildUtcPushSchedule(options);
}

export function buildLocalPushEvents({
  now = new Date(),
  daysBack = 4,
  existingItems = [],
  userId = "",
} = {}) {
  const existingById = new Map(existingItems.map((item) => [item.id, item]));
  const recent = recentMessageIdsFromItems(existingItems, now);
  const blockedIds = new Set(recent.messageIds);
  const blockedBodies = new Set(recent.bodies);
  const events = [];

  for (let offset = -daysBack; offset <= 0; offset += 1) {
    const day = addLocalDays(startOfLocalDay(now), offset);
    const dateKey = formatLocalDateKey(day);
    const slots = slotsForLocalDay(day);

    for (const slot of slots) {
      const sentAt = new Date(day);
      sentAt.setHours(slot.hour, slot.minute, 0, 0);
      if (sentAt > now) continue;

      const id = `${slot.kind}:${dateKey}:${slot.key}`;
      const existing = existingById.get(id);
      const message = existing?.data?.messageId
        ? { id: existing.data.messageId, body: existing.body }
        : pickPushMessage({
          kind: slot.kind,
          seed: `${userId || "anon"}:${dateKey}:${slot.key}`,
          blockedIds,
          blockedBodies,
        });
      blockedIds.add(message.id);
      blockedBodies.add(message.body);
      events.push({
        id,
        kind: slot.kind,
        title: "FruitFit",
        body: existing?.body || message.body,
        status: existing?.status || "sent",
        sentAt: existing?.sentAt || sentAt.toISOString(),
        readAt: existing?.readAt || null,
        data: {
          ...(existing?.data || {}),
          category: slot.kind,
          messageId: message.id,
          cadence: PUSH_CADENCE,
          dateKey,
          slot: slot.key,
          userScoped: true,
        },
      });
    }
  }

  return events.sort((a, b) => new Date(b.sentAt) - new Date(a.sentAt));
}

export function buildLocalMotivationEvents(options = {}) {
  return buildLocalPushEvents(options);
}

