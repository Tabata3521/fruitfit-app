function slotsForLocalDay(localDay) {
  const weekday = localDay.getDay ? localDay.getDay() : localDay.getUTCDay();
  const slots = PUSH_WINDOWS.daily_motivation.map((slot) => ({ ...slot, kind: "daily_motivation" }));

  for (const slot of PUSH_WINDOWS.discipline_gym_etiquette) {
    if (slot.weekday === weekday) slots.push({ ...slot, kind: "discipline_gym_etiquette" });
  }
  for (const slot of PUSH_WINDOWS.clarification_messages) {
    if (slot.weekday === weekday) slots.push({ ...slot, kind: "clarification_messages" });
  }

  return slots.sort((a, b) => (a.hour * 60 + a.minute) - (b.hour * 60 + b.minute));
}

function pickPushMessage({ kind, seed, blockedIds = new Set(), blockedBodies = new Set() }) {
  const library = PUSH_MESSAGE_LIBRARY[kind] || daily_motivation;
  for (let attempt = 0; attempt < library.length; attempt += 1) {
    const index = positiveHash(`${seed}:${attempt}`) % library.length;
    const message = library[index];
    if (!blockedIds.has(message.id) && !blockedBodies.has(message.body)) return message;
  }
  for (const message of library) {
    if (!blockedBodies.has(message.body)) return message;
  }
  return library[positiveHash(seed) % library.length];
}

function formatScheduleEvent({ slot, message, dateKey, scheduledAt, timezoneOffsetMinutes }) {
  return {
    kind: slot.kind,
    title: "FruitFit",
    body: message.body,
    scheduledAt: scheduledAt.toISOString(),
    data: {
      category: slot.kind,
      messageId: message.id,
      cadence: PUSH_CADENCE,
      dateKey,
      slot: slot.key,
      timezoneOffsetMinutes,
      userScoped: true,
      noRepeatDays: 7,
    },
  };
}

function recentMessageIdsFromItems(items = [], now = new Date()) {
  const since = now.getTime() - 7 * 86_400_000;
  const messageIds = [];
  const bodies = [];
  for (const item of items) {
    const at = new Date(item.sentAt || item.scheduledAt || item.createdAt || 0).getTime();
    if (!Number.isFinite(at) || at < since) continue;
    const messageId = item?.data?.messageId || item?.messageId;
    if (messageId) messageIds.push(messageId);
    if (item?.body) bodies.push(item.body);
  }
  return { messageIds, bodies };
}

function startOfLocalDay(date) {
  const next = new Date(date);
  next.setHours(0, 0, 0, 0);
  return next;
}

function addLocalDays(date, days) {
  const next = new Date(date);
  next.setDate(next.getDate() + days);
  return next;
}

function formatLocalDateKey(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function formatUtcDateKey(date) {
  const year = date.getUTCFullYear();
  const month = String(date.getUTCMonth() + 1).padStart(2, "0");
  const day = String(date.getUTCDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function positiveHash(value) {
  let hash = 0;
  for (let index = 0; index < String(value).length; index += 1) {
    hash = (hash << 5) - hash + String(value).charCodeAt(index);
    hash |= 0;
  }
  return Math.abs(hash);
}
