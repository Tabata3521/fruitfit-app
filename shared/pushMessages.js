function slotsForLocalDay(localDay) {
  const weekday = localDay.getDay ? localDay.getDay() : localDay.getUTCDay();
  const slots = PUSH_WINDOWS.daily_motivation.map((slot) => ({ ...slot, kind: "daily_motivation" }));

  for (const slot of PUSH_WINDOWS.discipline_gym_etiquette) {
    if (slot.weekday === weekday) slots.push({ ...slot, kind: "discipline_gym_etiquette" });
  }
  for (const slot of PUSH_WINDOWS.clarification_messages) {
    if (slot.weekday === weekday) slots.push({ ...slot, kind: "clarification_messages" });
  }

  return slots.sort((a, b) => (a.hour * 60 + a.minute) - (b.hour * 60 + b.minute));
}

function pickPushMessage({ kind, seed, blockedIds = new Set(), blockedBodies = new Set() }) {
  const library = PUSH_MESSAGE_LIBRARY[kind] || daily_motivation;
  for (let attempt = 0; attempt < library.length; attempt += 1) {
    const index = positiveHash(`${seed}:${attempt}`) % library.length;
    const message = library[index];
    if (!blockedIds.has(message.id) && !blockedBodies.has(message.body)) return message;
  }
  for (const message of library) {
    if (!blockedBodies.has(message.body)) return message;
  }
  return library[positiveHash(seed) % library.length];
}

