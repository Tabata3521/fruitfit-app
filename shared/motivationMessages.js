export const MOTIVATION_PUSH_WINDOWS = Object.freeze([
  { key: "morning", hour: 9, minute: 15 },
  { key: "day", hour: 14, minute: 10 },
  { key: "evening", hour: 19, minute: 20 }
]);

export function dailyMotivationCount(date) {
  const dayNumber = Math.floor(startOfLocalDay(date).getTime() / 86_400_000);
  return dayNumber % 3 === 0 ? 3 : 2;
}

export function pickMotivationMessage(seed, slotIndex, previousBody = "", usedBodies = new Set()) {
  for (let attempt = 0; attempt < MOTIVATION_MESSAGES.length; attempt += 1) {
    const index = positiveHash(`${seed}:${slotIndex}:${attempt}`) % MOTIVATION_MESSAGES.length;
    const body = MOTIVATION_MESSAGES[index];
    if (body !== previousBody && !usedBodies.has(body)) return body;
  }
  return MOTIVATION_MESSAGES[(slotIndex + 1) % MOTIVATION_MESSAGES.length];
}

export function buildLocalMotivationEvents({ now = new Date(), daysBack = 3, existingItems = [] } = {}) {
  const existingById = new Map(existingItems.map((item) => [item.id, item]));
  const events = [];
  let previousBody = existingItems[0]?.body || "";

  for (let offset = -daysBack; offset <= 0; offset += 1) {
    const day = addLocalDays(startOfLocalDay(now), offset);
    const count = dailyMotivationCount(day);
    const usedBodies = new Set();

    for (let slotIndex = 0; slotIndex < count; slotIndex += 1) {
      const window = MOTIVATION_PUSH_WINDOWS[slotIndex];
      const sentAt = new Date(day);
      sentAt.setHours(window.hour, window.minute, 0, 0);
      if (sentAt > now) continue;

      const id = `motivation:${formatLocalDateKey(day)}:${window.key}`;
      const existing = existingById.get(id);
      const body = existing?.body || pickMotivationMessage(formatLocalDateKey(day), slotIndex, previousBody, usedBodies);
      usedBodies.add(body);
      previousBody = body;
      events.push({
        id,
        kind: "motivation",
        title: "FruitFit",
        body,
        status: existing?.status || "sent",
        sentAt: existing?.sentAt || sentAt.toISOString(),
        readAt: existing?.readAt || null
      });
    }
  }

  return events.sort((a, b) => new Date(b.sentAt) - new Date(a.sentAt));
}

export function buildUtcMotivationSchedule({
  now = new Date(),
  days = 4,
  timezoneOffsetMinutes = 180,
  previousBody = ""
} = {}) {
  const localNow = new Date(now.getTime() + timezoneOffsetMinutes * 60_000);
  const startYear = localNow.getUTCFullYear();
  const startMonth = localNow.getUTCMonth();
  const startDate = localNow.getUTCDate();
  const events = [];
  let previous = previousBody;

  for (let dayOffset = 0; dayOffset < days; dayOffset += 1) {
    const localDay = new Date(Date.UTC(startYear, startMonth, startDate + dayOffset));
    const count = dailyMotivationCount(new Date(localDay.getTime() - timezoneOffsetMinutes * 60_000));
    const usedBodies = new Set();
    const dateKey = formatUtcDateKey(localDay);

    for (let slotIndex = 0; slotIndex < count; slotIndex += 1) {
      const window = MOTIVATION_PUSH_WINDOWS[slotIndex];
      const scheduledAt = new Date(Date.UTC(startYear, startMonth, startDate + dayOffset, window.hour, window.minute) - timezoneOffsetMinutes * 60_000);
      if (scheduledAt < now) continue;
      const body = pickMotivationMessage(dateKey, slotIndex, previous, usedBodies);
      usedBodies.add(body);
      previous = body;
      events.push({
        kind: "motivation",
        title: "FruitFit",
        body,
        scheduledAt: scheduledAt.toISOString(),
        data: {
          cadence: "2-3/day",
          dateKey,
          slot: window.key,
          timezoneOffsetMinutes
        }
      });
    }
  }

  return events;
}

function startOfLocalDay(date) {
  const next = new Date(date);
  next.setHours(0, 0, 0, 0);
  return next;
}

function addLocalDays(date, days) {
  const next = new Date(date);
  next.setDate(next.getDate() + days);
  return next;
}

function formatLocalDateKey(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function formatUtcDateKey(date) {
  const year = date.getUTCFullYear();
  const month = String(date.getUTCMonth() + 1).padStart(2, "0");
  const day = String(date.getUTCDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function positiveHash(value) {
  let hash = 0;
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash << 5) - hash + value.charCodeAt(index);
    hash |= 0;
  }
  return Math.abs(hash);
}
