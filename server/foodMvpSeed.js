const SOURCE = "ru_mvp_common_food_reference_v1";

function round(value, digits = 1) {
  const factor = 10 ** digits;
  return Math.round(Number(value || 0) * factor) / factor;
}

function product(name, category, kcal, protein, fat, carbs, aliases = [], serving = 100, source = SOURCE) {
  return {
    name,
    category,
    kcal: round(kcal),
    protein: round(protein),
    fat: round(fat),
    carbs: round(carbs),
    aliases: [...new Set([name.toLowerCase(), ...aliases])],
    defaultServingGrams: serving,
    servingExamples: [
      { label: `${serving} г`, grams: serving },
      { label: "100 г", grams: 100 },
    ],
    source,
  };
}

function scaleMacros(base, suffix, { kcal = 1, protein = 1, fat = 1, carbs = 1, fatAdd = 0 } = {}) {
  return product(
    `${base.name} ${suffix}`,
    base.category,
    base.kcal * kcal,
    base.protein * protein,
    base.fat * fat + fatAdd,
    base.carbs * carbs,
    [`${suffix} ${base.name}`.toLowerCase(), ...(base.aliases || []).map((item) => `${item} ${suffix}`)],
    base.serving,
  );
}

